export interface InboundResult {
  status: number;
  body: { ok: boolean; outcome?: InboundOutcome; ticket?: number; error?: string };
}

function secretMatches(given: string, stored: string): boolean {
  if (!stored || !given) return false;
  const a = Buffer.from(given);
  const b = Buffer.from(stored);
  return a.length === b.length && timingSafeEqual(a, b);
}

interface Sender {
  id: number;
  name: string;
  username: string;
  email: string;
  role: Role;
}

async function findSender(email: string): Promise<Sender | undefined> {
  if (!email) return undefined;
  return hqOne<Sender>(
    "SELECT id, name, username, email, role FROM users WHERE lower(email) = $1 AND status = 'active' ORDER BY id LIMIT 1",
    [email.toLowerCase()]
  );
}

/**
 * The team the mail was addressed to by its email alias (a full address or
 * just the local part), else `mailboxTeamId` (1.20.2: the team of the listed
 * address the mail was sent to, when that team still exists), else the
 * first team.
 */
export async function teamForRecipients(addresses: string[], mailboxTeamId: number | null = null): Promise<number | null> {
  const teams = await hq<{ id: number; email_alias: string }>("SELECT id, email_alias FROM hd_teams ORDER BY position, id");
  const lower = addresses.map((a) => a.toLowerCase());
  for (const t of teams) {
    const alias = t.email_alias.trim().toLowerCase();
    if (!alias) continue;
    const hit = alias.includes("@")
      ? lower.includes(alias)
      : lower.some((a) => a.split("@")[0].split("+")[0] === alias);
    if (hit) return t.id;
  }
  if (mailboxTeamId && teams.some((t) => t.id === mailboxTeamId)) return mailboxTeamId;
  return teams[0]?.id ?? null;
}

const reply = (status: number, body: InboundResult["body"]): InboundResult => ({ status, body });

/**
 * Handle one provider POST. `secret` is the path segment; `providerHint`
 * the `?provider=` the admin put on the URL ('' = recognise it); `origin`
 * the links' origin for the notices the new message sends.
 */
export async function handleInbound(req: Request, secret: string, opts: { providerHint?: string; origin?: string; ip?: string | null } = {}): Promise<InboundResult> {
  const settings = await getHelpdeskSettings();
  if (!secretMatches(secret, settings.inbound_secret)) return reply(404, { ok: false, error: "Not found." });
  if (!(await helpdeskLicensed())) return reply(402, { ok: false, error: "The helpdesk is not included in your licence." });
  if (limited("inbound:all", INBOUND_LIMITS.perMinute, 60_000)) return reply(429, { ok: false, error: "Too many messages. Try again shortly." });
  const length = Number(req.headers.get("content-length") || 0);
  if (length > INBOUND_MAX_BODY_BYTES) return reply(413, { ok: false, error: "The message is too large." });

  let email: InboundEmail;
  try {
    // The cap holds for a chunked body too (no Content-Length): read through it.
    email = await parseInboundRequest(req, opts.providerHint ?? "", INBOUND_MAX_BODY_BYTES);
  } catch (e) {
    if (e instanceof InboundTooLargeError) return reply(413, { ok: false, error: "The message is too large." });
    if (e instanceof InboundParseError) return reply(400, { ok: false, error: e.message });
    throw e;
  }
  return processInboundEmail(email, { origin: opts.origin, ip: opts.ip ?? null, outsideSenders: settings.outside_senders });
}

