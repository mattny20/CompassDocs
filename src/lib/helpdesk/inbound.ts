// Helpdesk inbound email (1.19.0): POST /api/helpdesk/inbound/<secret>.
// An email provider's inbound parse (Postmark, SendGrid, Mailgun, or any
// service that can POST the generic JSON) forwards each message here; this
// decides what it becomes.
//
//   1. The secret in the path must equal helpdesk_settings.inbound_secret
//      (timing-safe; anything else is a 404, so the URL is the credential).
//      Unlicensed: 402. Rate limits: 300 a minute for the endpoint, 20 per
//      sender per 10 minutes (429; providers retry later).
//   2. Auto-replies, bounces, list mail and our own outbound mail are
//      dropped (200, so the provider does not retry): two helpdesks must
//      never mail each other forever. A Message-ID seen before is a
//      provider retry: dropped as a duplicate.
//   3. The sender is matched to an active account by address, but only
//      when the mail provider's verdict shows the From domain authenticated
//      (DMARC pass, or SPF / DKIM pass aligned with it; see
//      lib/helpdesk/intake/email-rules authVerdict). With no verdict at all
//      the address is trusted only when Desk -> Settings -> Email "Trust
//      sender addresses without SPF/DKIM results" is on (off by default); a
//      failing verdict is never trusted. Unverified mail is mail from
//      outside the workspace: no account, the Outside senders rule applies,
//      and it is never added to an existing ticket.
//      A reply token (Reply-To plus tag, subject reference or In-Reply-To;
//      see lib/helpdesk/email) names a ticket: the verified requester's or
//      an agent's reply (one who may work it) is added to it, with the
//      quoted history cut; an agent's reply to an internal-note notice is
//      added as an internal note. A closed ticket gets a follow-up ticket
//      instead.
//   4. Otherwise a new ticket (source email): the team whose email alias
//      the mail was sent to, else the team of the listed address it was
//      sent to (1.20.2, lib/helpdesk/mailboxes: any listed address is
//      accepted on this one webhook, the ticket remembers which, and mail
//      to none of them counts as the default address), else the first
//      team. Rules, request types and automations run after, as before.
//      Mail From one of our own addresses that also carries a Message-ID
//      of ours (its own, In-Reply-To or References) or Auto-Submitted is
//      dropped as a loop and audited; From alone is not enough, that mail
//      is handled like any other. Someone with no account
//      is refused unless Outside senders is on (Desk → Settings → Email);
//      the refusal is logged and audited (helpdesk.inbound.rejected) and no
//      mail is sent back, since the From of unsolicited mail is easily
//      forged and a bounce would land on whoever was impersonated.
//   5. Attachments go to the helpdesk attachment store after the message
//      exists (count, size and type limits here; the store enforces its
//      own); the ones not added are listed in a note on the ticket.
//
// The body is text only: the text part, or the HTML part walked into text,
// escaped as markdown (lib/helpdesk/inbound-parse). Server-only.

