// --- Limits ----------------------------------------------------------------------

export const INBOUND_LIMITS = {
  files: 10,
  fileBytes: 10 * 1024 * 1024,
  totalBytes: 25 * 1024 * 1024,
  /** Images smaller than this are signature logos and spacer pixels: skipped silently. */
  tinyImageBytes: 4 * 1024,
  perMinute: 300,
  perSender: 20,
  perSenderWindowMs: 10 * 60_000,
} as const;

/** Extension -> the type it is stored and served as (never the sender's claim). */
const ALLOWED: Record<string, string> = {
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".pdf": "application/pdf",
  ".txt": "text/plain",
  ".log": "text/plain",
  ".csv": "text/csv",
  ".md": "text/plain",
  ".doc": "application/msword",
  ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  ".xls": "application/vnd.ms-excel",
  ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  ".ppt": "application/vnd.ms-powerpoint",
  ".pptx": "application/vnd.openxmlformats-officedocument.presentationml.presentation",
  ".odt": "application/vnd.oasis.opendocument.text",
  ".ods": "application/vnd.oasis.opendocument.spreadsheet",
  ".odp": "application/vnd.oasis.opendocument.presentation",
};

export const INBOUND_ALLOWED_EXTENSIONS = Object.keys(ALLOWED);

export interface AttachmentPlan {
  accept: { file: InboundFile; name: string; mime: string }[];
  /** "name (why)" for the note. */
  refused: string[];
}

function extOf(name: string): string {
  const m = name.toLowerCase().match(/\.[a-z0-9]{1,8}$/);
  return m ? m[0] : "";
}

/**
 * Which attachments to keep: an allowed extension whose content agrees
 * (images by their magic bytes, PDFs by "%PDF", Office files by their zip or
 * OLE header), within the count and size limits. Pure.
 */
export function planAttachments(files: InboundFile[]): AttachmentPlan {
  const plan: AttachmentPlan = { accept: [], refused: [] };
  let total = 0;
  for (const f of files) {
    const name = (f.name || "attachment").replace(/[\u0000-\u001f\\/]/g, "_").slice(0, 200);
    const ext = extOf(name);
    const mime = ALLOWED[ext];
    const isImage = mime?.startsWith("image/");
    if (isImage && f.data.length < INBOUND_LIMITS.tinyImageBytes) continue;
    if (!mime) {
      plan.refused.push(`${name} (file type not allowed)`);
      continue;
    }
    if (f.data.length === 0) {
      plan.refused.push(`${name} (empty)`);
      continue;
    }
    if (f.data.length > INBOUND_LIMITS.fileBytes) {
      plan.refused.push(`${name} (larger than ${INBOUND_LIMITS.fileBytes / 1024 / 1024} MB)`);
      continue;
    }
    if (!contentAgrees(ext, mime, f.data)) {
      plan.refused.push(`${name} (the content is not a ${ext.slice(1).toUpperCase()} file)`);
      continue;
    }
    if (plan.accept.length >= INBOUND_LIMITS.files) {
      plan.refused.push(`${name} (more than ${INBOUND_LIMITS.files} attachments)`);
      continue;
    }
    if (total + f.data.length > INBOUND_LIMITS.totalBytes) {
      plan.refused.push(`${name} (over ${INBOUND_LIMITS.totalBytes / 1024 / 1024} MB in total)`);
      continue;
    }
    total += f.data.length;
    plan.accept.push({ file: f, name, mime: isImage ? sniffImage(f.data)!.mime : mime });
  }
  return plan;
}

function contentAgrees(ext: string, mime: string, buf: Buffer): boolean {
  if (mime.startsWith("image/")) return sniffImage(buf) !== null;
  if (ext === ".pdf") return buf.subarray(0, 5).toString("latin1") === "%PDF-";
  if ([".docx", ".xlsx", ".pptx", ".odt", ".ods", ".odp"].includes(ext)) return buf.subarray(0, 4).equals(Buffer.from([0x50, 0x4b, 0x03, 0x04]));
  if ([".doc", ".xls", ".ppt"].includes(ext)) return buf.subarray(0, 8).equals(Buffer.from([0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1]));
  // Text: no NUL bytes in the first 8 KB, and nothing that starts like markup a browser would run.
  const head = buf.subarray(0, 8192);
  if (head.includes(0)) return false;
  return !/^\s*<(!doctype|html|script|svg)/i.test(head.toString("utf8"));
}

