/**
 * Settings key of the email channel's sender-authentication choice. Kept
 * apart from helpdesk_settings (whose shape lib/helpdesk/settings owns).
 */
export const HD_INBOUND_AUTH_KEY = "helpdesk_inbound_auth";

export interface InboundAuthSettings {
  /**
   * Mail whose provider reports no SPF, DKIM or DMARC result at all is
   * matched to the account of its From address. Off by default: anyone can
   * write any From address. A failing result is never trusted.
   */
  trust_unverified_senders: boolean;
}

export async function getInboundAuthSettings(): Promise<InboundAuthSettings> {
  try {
    const raw = await getSetting(HD_INBOUND_AUTH_KEY);
    const v = raw ? JSON.parse(raw) : {};
    return { trust_unverified_senders: v?.trust_unverified_senders === true };
  } catch {
    return { trust_unverified_senders: false };
  }
}

/** Save the choice; answers whether it changed. */
export async function saveInboundAuthSettings(patch: Partial<InboundAuthSettings>): Promise<{ settings: InboundAuthSettings; changed: boolean }> {
  const before = await getInboundAuthSettings();
  const next: InboundAuthSettings = {
    trust_unverified_senders: patch.trust_unverified_senders === undefined ? before.trust_unverified_senders : patch.trust_unverified_senders === true,
  };
  const changed = next.trust_unverified_senders !== before.trust_unverified_senders;
  if (changed) await setSetting(HD_INBOUND_AUTH_KEY, JSON.stringify(next));
  return { settings: next, changed };
}

