/** addMessage refused the reply because its ticket was merged meanwhile, before writing anything. */
async function mergeRaced(e: unknown): Promise<boolean> {
  const { HdTicketError } = await import("./tickets");
  return e instanceof HdTicketError && e.status === 409 && e.messageUnsent === true;
}

const OUR_MESSAGE_ID = /^<?hd(?:\.[a-z0-9]{16}\.|-note-[a-z0-9]{16}-)/i;

/**
 * What marks a mail as one of the desk's own besides its From address: a
 * Message-ID of ours (<hd.TOKEN.…@…>, <hd-note-TOKEN-…@…>) as its own or in
 * In-Reply-To / References, or an Auto-Submitted header. Null when nothing
 * does.
 */
export function ownMailSignal(email: Pick<InboundEmail, "messageId" | "inReplyTo" | "references" | "headers">): "message_id" | "thread" | "auto_submitted" | null {
  if (OUR_MESSAGE_ID.test((email.messageId ?? "").trim())) return "message_id";
  if ([email.inReplyTo ?? "", ...(email.references ?? [])].some((id) => OUR_MESSAGE_ID.test(id.trim()))) return "thread";
  const auto = (email.headers?.["auto-submitted"] ?? "").trim().toLowerCase();
  if (auto && auto !== "no") return "auto_submitted";
  return null;
}

/** Everything after parsing (tests call it with an InboundEmail of their own). */
export async function processInboundEmail(
  email: InboundEmail,
  opts: {
    origin?: string;
    ip?: string | null;
    outsideSenders?: boolean;
    trustUnverified?: boolean;
    /** Internal: the one retry after a merge raced the reply (not counted against the sender again, never retried again). */
    mergeRetry?: boolean;
  } = {}
): Promise<InboundResult> {
  const outsideSenders = opts.outsideSenders ?? (await getHelpdeskSettings()).outside_senders;
  if (email.headers["x-compassdocs-helpdesk"]) return reply(200, { ok: true, outcome: "ignored_loop" });
  // 1.20.2: mail From one of our own addresses (a listed mailbox or a ticket
  // reply address) is our own mail coming back, or a forward loop between
  // two of them, only when something else says so too: a Message-ID of ours
  // on it or in its thread headers, or Auto-Submitted. (Our own header was
  // answered one line up.) The address alone proves nothing: a colleague
  // writing as the shared mailbox, or a group that rewrites From, is real
  // mail and goes on as any other. A dropped one is audited.
  const mailboxes = await import("./mailboxes");
  const loop = ownMailSignal(email);
  if (loop && (await mailboxes.isOwnAddress(email.from.email))) {
    logEvent("info", "helpdesk.inbound_ignored", { reason: "own_address", signal: loop, from: email.from.email, provider: email.provider });
    await audit({
      actor: { name: "inbound email" },
      action: "helpdesk.inbound.rejected",
      targetType: "helpdesk_inbound",
      targetLabel: email.from.email,
      details: { reason: "own_address_loop", signal: loop, from: email.from.email, subject: email.subject.slice(0, 200), provider: email.provider },
      ip: opts.ip ?? null,
    }).catch(() => {});
    return reply(200, { ok: true, outcome: "ignored_loop" });
  }
  // A monitoring tool's mail from an address an email integration lists is
  // an alert, auto-generated or not (SPF/DKIM must pass when reported).
  const { intakeFromEmail } = await import("./intake/email");
  const machine = await intakeFromEmail(email, { origin: opts.origin, ip: opts.ip ?? null });
  if (machine) return reply(machine.status, machine.body);
  if (isAutoGenerated(email)) {
    logEvent("info", "helpdesk.inbound_ignored", { reason: "auto", from: email.from.email, provider: email.provider });
    return reply(200, { ok: true, outcome: "ignored_auto" });
  }
  if (email.messageId) {
    const seen = await hqOne("SELECT 1 FROM hd_messages WHERE email_message_id = $1 LIMIT 1", [email.messageId.slice(0, 500)]);
    if (seen) return reply(200, { ok: true, outcome: "duplicate" });
  }
  if (!opts.mergeRetry && limited(`inbound:from:${email.from.email}`, INBOUND_LIMITS.perSender, INBOUND_LIMITS.perSenderWindowMs)) {
    return reply(429, { ok: false, error: "Too many messages from this sender. Try again later." });
  }

  // Who wrote it: the From address counts only when the provider's verdict
  // authenticates its domain (or, with no verdict at all, when the admin
  // chose to trust addresses). Anything else is an outside sender.
  const trustUnverified = opts.trustUnverified ?? (await getInboundAuthSettings()).trust_unverified_senders;
  const verdict = emailAuthVerdict(email);
  const verified = verdict.ok || (verdict.state === "none" && trustUnverified);
  const claimed = await findSender(email.from.email);
  const sender = verified ? claimed : undefined;
  if (claimed && !verified) {
    logEvent("warn", "helpdesk.inbound_unverified", { from: email.from.email, provider: email.provider, state: verdict.state, verdict: verdict.reason });
  }
  const authorName = sender ? sender.name || sender.username : email.from.name || email.from.email;
  const author = { id: sender?.id ?? null, name: authorName.slice(0, 200), email: email.from.email };
  const messageId = email.messageId ? email.messageId.slice(0, 500) : null;

  // A reply to a ticket?
  const token = findReplyToken(email);
  // 1.19.2 (agent W5, lib/helpdesk/reply-all): no token, but a verified
  // sender's In-Reply-To/References name an email that opened (or was added
  // to) a ticket: a colleague's Reply all before the desk answered. The
  // same authority rules as a token reply follow.
  const threadTicketId = !token && verified ? await (await import("./reply-all")).ticketForReplyAll(email) : null;
  let followUpOf: number | null = null;
  // 1.19.1 review (lib/helpdesk/portal-hooks): the portal contact whose
  // closed ticket this follows up; the follow-up opens as their portal ticket.
  let portalFollowUp: { contactId: number; teamId: number | null } | null = null;
  // 1.19.4 (C7): a reply to a ticket in the recycle bin opens a new ticket, never naming the binned one.
  let binnedReply = false;
  // 1.20.2: the closed (or binned) ticket a follow-up continues: its address stands in when the mail names none.
  let followUpMailboxId: number | null = null;
  if (token && !verified) {
    // Never into an existing ticket on an unverified From: the token is in
    // every copy of the thread, so anyone on it could write as anyone.
    logEvent("info", "helpdesk.inbound_unverified_reply", { from: email.from.email, state: verdict.state });
  } else if (token || threadTicketId) {
    const replied = threadTicketId
      ? await hqOne<HdTicketRow>("SELECT * FROM hd_tickets WHERE id = $1", [threadTicketId])
      : await hqOne<HdTicketRow>("SELECT * FROM hd_tickets WHERE reply_token = $1", [token]);
    // A merged ticket's thread replies into the ticket it was merged into,
    // where its requester counts as one (1.19.1, lib/helpdesk/merge).
    const t = replied ? await (await import("./merge")).mergedReplyTarget(replied) : undefined;
    // 1.19.4 (C7): a reply to a ticket in the recycle bin opens a new ticket below (as an
    // unthreaded mail does); it never restores the binned one or adds to it.
    const binned = !!(replied?.deleted_at || t?.deleted_at);
    followUpMailboxId = t?.mailbox_id ?? replied?.mailbox_id ?? null;
    if (binned) {
      binnedReply = true;
      logEvent("info", "helpdesk.inbound_binned_reply", { ticket: t?.number ?? replied?.number, from: email.from.email });
      // A portal contact's own request: a portal follow-up, as for a closed one (Outside senders doesn't apply).
      if (!sender) {
        for (const x of [t, replied]) {
          if (!x?.portal_contact_id) continue;
          const portal = await (await import("./portal-hooks")).portalReplyAuthority(x, email.from.email, { binned: true });
          if (portal?.allowed && portal.contactId) {
            portalFollowUp = { contactId: portal.contactId, teamId: x.team_id };
            break;
          }
        }
      }
    }
    if (t && replied && !binned) {
      const reqOf = (x: HdTicketRow) =>
        (sender && x.requester_id === sender.id) ||
        (!sender && x.requester_id === null && outsideSenders && x.requester_email.toLowerCase() === email.from.email);
      // 1.19.1 (agent V6, lib/helpdesk/portal-hooks): on a customer-portal
      // ticket only its own contact (verified above, no account, not
      // blocked) is the requester, whatever Outside senders says; so is the
      // contact of a portal ticket merged into this one. Only while the
      // portal is open and admits the address (else null: the rules below).
      // A blocked contact is refused as a CC too.
      const portal = sender ? null : await (await import("./portal-hooks")).portalReplyAuthority(t, email.from.email);
      const isRequester = portal ? portal.allowed : reqOf(t) || (replied !== t && reqOf(replied));
      const isAgent = !isRequester && sender ? await canWorkTicket(sender, t) : false;
      // 1.19.1 (agent V3, lib/helpdesk/ccs): someone copied on the request
      // (an account, or an outside address while outside senders are on)
      // replies as the requester does. Verified senders only, as above.
      const isCc =
        !isRequester && !isAgent && !portal?.blocked && (sender || outsideSenders)
          ? await import("./ccs").then((m) => m.isCcAuthor(t.id, sender?.id ?? null, email.from.email))
          : false;
      if (isRequester || isAgent || isCc) {
        if (t.status === "closed") {
          followUpOf = t.number;
          if (portal?.allowed && portal.contactId) portalFollowUp = { contactId: portal.contactId, teamId: t.team_id };
        } else {
          const { addMessage } = await import("./messages");
          // An agent answering an internal-note notice (agent S3's
          // hd_internal_note mail) writes an internal note, never to the requester.
          const toNote = Boolean(isAgent) && [email.inReplyTo, ...email.references].some((id) => isNoteNoticeMessageId(id));
          await beforeAppendForTests?.(t.id);
          let r: Awaited<ReturnType<typeof addMessage>>;
          try {
            r = await addMessage(
              t.id,
              {
                kind: toNote ? "internal" : "public",
                body: inboundBody(email, { reply: true }) || "_(empty reply)_",
                author,
                via: "email",
                asRequester: Boolean(isRequester || isCc),
                email_message_id: messageId,
              },
              {
                origin: opts.origin,
                actorId: author.id,
                actorName: author.name,
                // 1.19.2 (agent W5): a reply-all already reached its own To/Cc; the notice mails them no copy.
                directRecipients: threadTicketId ? (await import("./reply-all")).directRecipients(email) : undefined,
              }
            );
          } catch (e) {
            // 1.19.1: a merge committed between the lookup above and the
            // message (tickets assertNotMergedTx, before anything was
            // written). Once: the whole decision again, so the thread now
            // leads to the kept ticket under the checks any reply there
            // meets (requester, agent, CC; closed: a follow-up). Anything
            // else fails as before.
            if (opts.mergeRetry || !(await mergeRaced(e))) throw e;
            logEvent("info", "helpdesk.inbound_merge_retry", { ticket: t.number, from: email.from.email });
            return processInboundEmail(email, { ...opts, outsideSenders, trustUnverified, mergeRetry: true });
          }
          if (r) await storeAttachments(email, t.id, r.message.id, author.id);
          // 1.19.4 (C7): binned between the lookup and the append (addMessage found no live row): a new ticket below.
          if (r || !(await (await import("./recycle-bin-guard")).ticketIsBinned({ id: t.id }))) {
            return reply(200, { ok: true, outcome: "appended", ticket: t.number });
          }
        }
      } else {
        // Somebody who is neither the requester, a CC nor an agent of it:
        // their mail becomes a ticket of their own, never a message on
        // somebody else's.
        logEvent("info", "helpdesk.inbound_not_on_ticket", { ticket: t.number, from: email.from.email });
      }
    }
  }

  // A new ticket.
  // 1.19.1 (agent V6): a blocked customer-portal contact opens nothing by email either.
  if (!sender && outsideSenders && (await (await import("./portal-hooks")).portalContactBlocked(email.from.email))) {
    logEvent("warn", "helpdesk.inbound_rejected", { reason: "portal_contact_blocked", from: email.from.email, provider: email.provider });
    return reply(200, { ok: true, outcome: "rejected_outside_sender" });
  }
  // 1.20.2: the listed address the mail was sent to (else the thread's, else
  // the default) is the ticket's mailbox, and its team the fallback before
  // the first team.
  const recipients = [...email.to.map((a) => a.email), ...email.cc.map((a) => a.email), ...email.recipients];
  const box = await mailboxes.mailboxForInbound(email);
  const threadBox = box && !box.matched && followUpMailboxId ? await mailboxes.getMailbox(followUpMailboxId) : undefined;
  const mailbox = threadBox ?? box?.mailbox ?? null;
  if (portalFollowUp) {
    const { createPortalFollowUp } = await import("./portal-hooks");
    const body = followUpOf !== null ? `_Follow-up to #${followUpOf}, which was closed._\n\n${inboundBody(email, { reply: true })}` : inboundBody(email, { reply: true });
    const teamId = (await teamForRecipients(recipients, mailbox?.team_id ?? null)) ?? portalFollowUp.teamId;
    const ticket = await createPortalFollowUp(
      portalFollowUp.contactId,
      {
        subject: (cleanSubject(email.subject) || "(no subject)").slice(0, 300),
        body,
        name: author.name,
        email: email.from.email,
        teamId,
        emailMessageId: messageId,
        closedNumber: followUpOf,
        mailboxId: mailbox?.id ?? null,
      },
      { origin: opts.origin }
    );
    const first = await hqOne<{ id: number }>("SELECT id FROM hd_messages WHERE ticket_id = $1 AND kind <> 'system' ORDER BY created_at, id LIMIT 1", [ticket.id]);
    if (first) await storeAttachments(email, ticket.id, first.id, null);
    return reply(200, { ok: true, outcome: "follow_up", ticket: ticket.number });
  }
  if (!sender && !outsideSenders) {
    const reason = claimed ? "unverified_sender" : "outside_sender";
    logEvent("warn", "helpdesk.inbound_rejected", { reason, from: email.from.email, provider: email.provider });
    await audit({
      actor: { name: "inbound email" },
      action: "helpdesk.inbound.rejected",
      targetType: "helpdesk_inbound",
      targetLabel: email.from.email,
      details: {
        reason,
        from: email.from.email,
        subject: email.subject.slice(0, 200),
        provider: email.provider,
        ...(claimed ? { sender_check: verdict.state, verdict: verdict.reason.slice(0, 200) } : {}),
      },
      ip: opts.ip ?? null,
    });
    return reply(200, { ok: true, outcome: "rejected_outside_sender" });
  }
  if (sender && !(await canUseHelpdesk(sender))) {
    logEvent("warn", "helpdesk.inbound_rejected", { reason: "not_permitted", from: email.from.email });
    await audit({
      actor: { id: sender.id, name: authorName, role: sender.role },
      action: "helpdesk.inbound.rejected",
      targetType: "helpdesk_inbound",
      targetLabel: email.from.email,
      details: { reason: "not_permitted", from: email.from.email, provider: email.provider },
      ip: opts.ip ?? null,
    });
    return reply(200, { ok: true, outcome: "rejected_not_permitted" });
  }

  const teamId = await teamForRecipients(recipients, mailbox?.team_id ?? null);
  // A reply's quoted thread stays out (1.19.4: so a binned conversation never comes back in a new ticket).
  let body = inboundBody(email, { reply: followUpOf !== null || binnedReply });
  if (followUpOf !== null) body = `_Follow-up to #${followUpOf}, which was closed._\n\n${body}`;
  const subject = cleanSubject(email.subject) || "(no subject)";
  const { createTicket } = await import("./tickets");
  const ticket = await createTicket(
    {
      subject: subject.slice(0, 300),
      body: body || "_(empty email)_",
      requester: { id: sender?.id ?? null, name: author.name, email: email.from.email },
      via: "email",
      source: "email",
      team_id: teamId,
      mailbox_id: mailbox?.id ?? null,
      email_message_id: messageId,
    },
    { origin: opts.origin, actorId: author.id, actorName: author.name }
  );
  const first = await hqOne<{ id: number }>(
    "SELECT id FROM hd_messages WHERE ticket_id = $1 AND kind <> 'system' ORDER BY created_at, id LIMIT 1",
    [ticket.id]
  );
  if (first) await storeAttachments(email, ticket.id, first.id, author.id);
  // The mail's Cc become the request's CCs (1.19.1, agent V3), only when the
  // sender is verified; outside addresses only while outside senders are on.
  if (verified) {
    const { ccsFromInbound } = await import("./ccs");
    await ccsFromInbound(ticket.id, email, { userId: sender?.id ?? null, name: author.name }, { outsideSenders }).catch((e) =>
      logEvent("error", "helpdesk.inbound_cc_failed", { ticket: ticket.number, error: e instanceof Error ? e.message : String(e) })
    );
  }
  if (claimed && !sender) {
    const { addSystemMessage } = await import("./messages");
    await addSystemMessage(
      ticket.id,
      verdict.state === "none"
        ? "The sender's address belongs to a workspace account, but the mail provider reported no SPF, DKIM or DMARC result, so this was treated as mail from outside the workspace. Check with them before acting on it."
        : `The sender's address belongs to a workspace account, but it failed the sender check (${mdInline(verdict.reason.slice(0, 200))}), so this was treated as mail from outside the workspace. It may be forged.`,
      { internal: true }
    );
  }
  return reply(200, { ok: true, outcome: followUpOf !== null ? "follow_up" : "created", ticket: ticket.number });
}

/** Save the attachments that pass, bind them to the message, and note the ones that did not. */
async function storeAttachments(email: InboundEmail, ticketId: number, messageId: number, userId: number | null): Promise<void> {
  if (!email.files.length) return;
  const plan = planAttachments(email.files);
  const refused = [...plan.refused];
  const saved: number[] = [];
  const store = await attachmentStore();
  for (const a of plan.accept) {
    try {
      const att = await store.save({ buf: a.file.data, filename: a.name, mime: a.mime, ticketId, userId });
      saved.push(att.id);
    } catch (e) {
      refused.push(`${a.name} (${e instanceof Error ? e.message : "could not be stored"})`);
    }
  }
  if (saved.length) {
    try {
      const bound = await store.bind(saved, ticketId, messageId);
      // The message lists its files (what the conversation renders).
      if (bound.length) {
        await hq("UPDATE hd_messages SET attachments = attachments || $2::jsonb WHERE id = $1", [messageId, JSON.stringify(bound)]);
      }
    } catch (e) {
      logEvent("error", "helpdesk.inbound_attach_failed", { ticket_id: ticketId, error: e instanceof Error ? e.message : String(e) });
    }
  }
  if (refused.length) {
    const { addSystemMessage } = await import("./messages");
    const list = refused.slice(0, 20).map((r) => `- ${escapeInline(r)}`).join("\n");
    await addSystemMessage(
      ticketId,
      `${refused.length === 1 ? "1 attachment was" : `${refused.length} attachments were`} not added from the email:\n\n${list}`
    );
  }
}
