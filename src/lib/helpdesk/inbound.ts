// --- Rate limits -----------------------------------------------------------------

const buckets = new Map<string, { count: number; resetAt: number }>();

function limited(key: string, max: number, windowMs: number, now = Date.now()): boolean {
  let w = buckets.get(key);
  if (!w || now >= w.resetAt) {
    w = { count: 0, resetAt: now + windowMs };
    buckets.set(key, w);
  }
  w.count++;
  if (buckets.size > 10_000) for (const [k, v] of buckets) if (now >= v.resetAt) buckets.delete(k);
  return w.count > max;
}

/** Tests: forget the counters. */
export function resetInboundRateLimitsForTests(): void {
  buckets.clear();
}

