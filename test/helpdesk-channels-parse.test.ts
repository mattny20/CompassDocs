describe("provider payloads", () => {
  test("generic JSON", async () => {
    const req = new Request("http://x/api/helpdesk/inbound/s", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        from: '"Felix, Matthew" <Matthew@Example.test>',
        to: "IT Desk <it@example.test>, help@example.test",
        subject: "Printer\r\nBcc: evil@example.test",
        text: "Out of toner",
        message_id: "<m1@example.test>",
        in_reply_to: "<hd.k7q2xz9m4pqa1b2c.ab12@example.test>",
        attachments: [{ filename: "a.pdf", content_type: "application/pdf", content: PDF.toString("base64") }],
      }),
    });
    const e = await parseInboundRequest(req);
    assert.equal(e.provider, "generic");
    assert.deepEqual(e.from, { email: "matthew@example.test", name: "Felix, Matthew" });
    assert.deepEqual(e.to.map((a) => a.email), ["it@example.test", "help@example.test"]);
    assert.equal(e.subject, "Printer Bcc: evil@example.test", "no header injection through the subject");
    assert.equal(e.messageId, "m1@example.test");
    assert.equal(e.files[0].data.subarray(0, 5).toString(), "%PDF-");
    assert.equal(findReplyToken(e), TOKEN, "In-Reply-To names our Message-ID");
  });

  test("Postmark JSON", async () => {
    const req = new Request("http://x", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        FromFull: { Email: "priya@example.test", Name: "Priya Shah" },
        ToFull: [{ Email: `help+hd-${TOKEN}@example.test`, Name: "", MailboxHash: `hd-${TOKEN}` }],
        CcFull: [],
        Subject: "Re: VPN",
        MessageID: "postmark-internal-id",
        TextBody: "Thanks!\n\nOn Mon, 3 Nov 2026 at 10:11, Desk <help@example.test> wrote:\n> old",
        HtmlBody: "<p>Thanks!</p>",
        StrippedTextReply: "Thanks!",
        Headers: [
          { Name: "Message-ID", Value: "<pm-1@mail.example.test>" },
          { Name: "In-Reply-To", Value: "<x@y>" },
        ],
        Attachments: [{ Name: "shot.png", ContentType: "image/png", Content: PNG.toString("base64"), ContentLength: PNG.length }],
      }),
    });
    const e = await parseInboundRequest(req);
    assert.equal(e.provider, "postmark");
    assert.equal(e.from.email, "priya@example.test");
    assert.equal(e.messageId, "pm-1@mail.example.test", "the header, not Postmark's own id");
    assert.equal(e.stripped, "Thanks!");
    assert.equal(findReplyToken(e), TOKEN, "the plus tag of the recipient");
    assert.equal(e.files.length, 1);
    assert.equal(inboundBody(e, { reply: true }), "Thanks\\!");
  });

  test("SendGrid inbound parse (multipart)", async () => {
    const form = new FormData();
    form.set("from", "Dana Whitfield <dana@example.test>");
    form.set("to", "help@example.test");
    form.set("cc", "");
    form.set("subject", `Re: Laptop [#1047 ref:${TOKEN}]`);
    form.set("text", "Yes please");
    form.set("html", "<p>Yes please</p>");
    form.set("headers", "Message-ID: <sg-1@example.test>\r\nReferences: <a@b>\r\n <hd.k7q2xz9m4pqa1b2c.root@example.test>\r\nAuto-Submitted: no\r\n");
    form.set("envelope", JSON.stringify({ to: ["help@example.test"], from: "dana@example.test" }));
    form.set("attachments", "1");
    form.set("attachment-info", JSON.stringify({ attachment1: { filename: "notes.txt", type: "text/plain" } }));
    form.set("attachment1", new Blob(["hello"], { type: "text/plain" }), "notes.txt");
    const e = await parseInboundRequest(new Request("http://x", { method: "POST", body: form }));
    assert.equal(e.provider, "sendgrid");
    assert.equal(e.messageId, "sg-1@example.test");
    assert.deepEqual(e.references, ["a@b", `hd.${TOKEN}.root@example.test`], "folded header unfolded");
    assert.equal(findReplyToken(e), TOKEN);
    assert.equal(e.files[0].name, "notes.txt");
    assert.equal(e.files[0].data.toString(), "hello");
    assert.equal(isAutoGenerated(e), false, "Auto-Submitted: no is a person");
  });

  test("Mailgun forward (multipart)", async () => {
    const form = new FormData();
    form.set("sender", "ben@example.test");
    form.set("from", "Ben Lo <ben@example.test>");
    form.set("recipient", "it@example.test");
    form.set("subject", "Keyboard");
    form.set("body-plain", "Broken key");
    form.set("stripped-text", "Broken key");
    form.set("Message-Id", "<mg-1@example.test>");
    form.set("message-headers", JSON.stringify([["Precedence", "bulk"]]));
    form.set("attachment-count", "1");
    form.set("attachment-1", new Blob([PDF], { type: "application/pdf" }), "receipt.pdf");
    const e = await parseInboundRequest(new Request("http://x", { method: "POST", body: form }));
    assert.equal(e.provider, "mailgun");
    assert.equal(e.from.name, "Ben Lo");
    assert.deepEqual(e.recipients, ["it@example.test"]);
    assert.equal(e.messageId, "mg-1@example.test");
    assert.equal(e.files[0].name, "receipt.pdf");
    assert.equal(isAutoGenerated(e), true, "Precedence: bulk is not a person");
  });

  test("the ?provider= hint wins and junk is refused", async () => {
    await assert.rejects(parseInboundRequest(new Request("http://x", { method: "POST", headers: { "content-type": "text/plain" }, body: "hi" })));
    await assert.rejects(
      parseInboundRequest(new Request("http://x", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ subject: "no sender" }) }))
    );
    const e = await parseInboundRequest(
      new Request("http://x", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ from: "a@example.test", TextBody: "x" }) }),
      "generic"
    );
    assert.equal(e.provider, "generic");
  });

  test("address lists keep quoted commas", () => {
    assert.deepEqual(parseAddressList('"Shah, Priya" <p@example.test>, b@example.test').map((a) => a.email), ["p@example.test", "b@example.test"]);
  });
});

describe("loops and tokens", () => {
  test("auto-replies, bounces and lists are not people", () => {
    assert.equal(isAutoGenerated(email({ headers: { "auto-submitted": "auto-replied" } })), true);
    assert.equal(isAutoGenerated(email({ headers: { "x-autoreply": "yes" } })), true);
    assert.equal(isAutoGenerated(email({ headers: { "list-id": "<x.example.test>" } })), true);
    assert.equal(isAutoGenerated(email({ from: { email: "mailer-daemon@example.test", name: "" } })), true);
    assert.equal(isAutoGenerated(email()), false);
  });

  test("tokens: subject reference, plus tag, our Message-ID; nothing else", () => {
    assert.equal(findReplyToken(email({ subject: `Re: x [#1047 ref:${TOKEN.toUpperCase()}]` })), TOKEN);
    assert.equal(findReplyToken(email({ cc: [{ email: `desk+hd-${TOKEN}@example.test`, name: "" }] })), TOKEN);
    assert.equal(findReplyToken(email({ subject: "Re: #1047" })), null, "a number alone is not a token");
    assert.equal(findReplyToken(email({ subject: "[#1047 ref:short]" })), null);
  });

  test("subjects lose the reference and the Re:/Fwd: prefixes", () => {
    assert.equal(cleanSubject(`RE: Fwd: AW: VPN drops [#1047 ref:${TOKEN}]`), "VPN drops");
  });

  test("reply addresses and references", () => {
    assert.equal(replyToAddress("Help@Example.test", TOKEN), `help+hd-${TOKEN}@example.test`);
    assert.equal(replyToAddress("help+old@example.test", TOKEN), `help+hd-${TOKEN}@example.test`);
    assert.equal(replyToAddress("not an address", TOKEN), null);
    assert.equal(threadRef(1047, TOKEN), `[#1047 ref:${TOKEN}]`);
    assert.match(newReplyToken(), /^[a-z0-9]{16}$/);
  });
});

describe("HTML and markdown safety", () => {
  const hostile =
    '<html><head><style>p{color:red}</style><script>alert(1)</script></head><body>' +
    '<p>Hello <b>team</b>,</p><p>See <a href="https://example.test/kb">the article</a> and <a href="javascript:alert(2)">this</a>.</p>' +
    '<img src="https://tracker.example.test/pixel.gif"><ul><li>one</li><li>two</li></ul>' +
    '<div class="gmail_quote">On Mon, someone wrote:<blockquote>old stuff</blockquote></div></body></html>';

  test("HTML becomes text: no script, no style, no image, links named", () => {
    const text = htmlToText(hostile, { dropQuotes: true });
    assert.ok(!/alert|color:red|tracker|<|>/.test(text), text);
    assert.match(text, /Hello team,/);
    assert.match(text, /the article \(https:\/\/example\.test\/kb\)/);
    assert.match(text, /- one\n- two/);
    assert.ok(!text.includes("old stuff"), "the Gmail quote is gone");
    assert.ok(htmlToText(hostile).includes("old stuff"), "kept when not a reply");
  });

  test("text renders as itself through the app's markdown pipeline", async () => {
    const nasty = "# Not a heading\n[click](javascript:alert(1)) ![x](https://tracker.example.test/p.gif)\n<script>alert(1)</script> **bold** `code`\n1. not a list\n- not a bullet\n&lt;b&gt; and https://example.test/a_b_c";
    const md = textToSafeMarkdown(nasty);
    const html = await renderBodyHtml(md, "#2563eb", "https://docs.example.test");
    assert.ok(!/<h1|<img|<script|<strong|<code|<ol|<ul|href="javascript/i.test(html), html);
    assert.ok(!html.includes('src="https://tracker'), "no image from markdown syntax (a URL written out may autolink)");
    assert.match(html, /https:\/\/example\.test\/a_b_c/, "bare URLs stay as written");
    assert.ok(html.includes("&#x3C;script>") || html.includes("&lt;script&gt;"), "the tag is text");
    assert.equal(markdownToPlain(md), nasty, "and the notification email quotes the original text");
  });

  test("an empty text part falls back to the HTML part", () => {
    const body = inboundBody(email({ text: "", html: "<p>Only <i>html</i></p>" }), { reply: false });
    assert.equal(body, "Only html");
  });
});

describe("quoted replies", () => {
  test("Gmail, wrapped Gmail, Outlook, bottom quotes and signatures", () => {
    assert.equal(stripQuotedReply("Works now.\n\nOn Mon, 3 Nov 2026 at 10:11, Priya <p@x> wrote:\n> Try again"), "Works now.");
    assert.equal(stripQuotedReply("Works.\n\nOn Mon, 3 Nov 2026 at 10:11, Priya Shah <\npriya@example.test> wrote:\n> x"), "Works.");
    assert.equal(
      stripQuotedReply("Sure.\n\n________________________________\nFrom: Desk <help@x>\nSent: Monday\nTo: Me\nSubject: Re: x\n\nold"),
      "Sure."
    );
    assert.equal(stripQuotedReply("Fixed, thanks\n\n> earlier\n> lines\n"), "Fixed, thanks");
    assert.equal(stripQuotedReply("Done.\n-- \nMatthew Felix\nPhoenix office"), "Done.");
    assert.equal(stripQuotedReply("> only a quote"), "> only a quote", "never strips everything");
  });
});

describe("attachment plan", () => {
  test("type, content, size and count limits", () => {
    const files = [
      { name: "shot.png", type: "image/png", data: PNG },
      { name: "virus.exe", type: "application/octet-stream", data: Buffer.from("MZ....") },
      { name: "fake.png", type: "image/png", data: Buffer.alloc(9000, 7) },
      { name: "page.txt", type: "text/plain", data: Buffer.from("<html><script>x</script>") },
      { name: "logo.png", type: "image/png", data: PNG.subarray(0, 100) },
      { name: "big.pdf", type: "application/pdf", data: Buffer.concat([PDF, Buffer.alloc(INBOUND_LIMITS.fileBytes)]) },
      { name: "invoice.pdf", type: "text/html", data: PDF },
    ];
    const plan = planAttachments(files);
    assert.deepEqual(plan.accept.map((a) => [a.name, a.mime]), [
      ["shot.png", "image/png"],
      ["invoice.pdf", "application/pdf"],
    ]);
    assert.deepEqual(plan.refused, [
      "virus.exe (file type not allowed)",
      "fake.png (the content is not a PNG file)",
      "page.txt (the content is not a TXT file)",
      "big.pdf (larger than 10 MB)",
    ]);
    const many = Array.from({ length: 12 }, (_, i) => ({ name: `f${i}.pdf`, type: "", data: PDF }));
    const p2 = planAttachments(many);
    assert.equal(p2.accept.length, INBOUND_LIMITS.files);
    assert.equal(p2.refused.length, 2);
  });
});

describe("email templates", () => {
  const hd = EMAIL_TEMPLATES.filter((t) => t.key.startsWith("hd_"));

  test("every hd_* template documents its tags and has sample values", () => {
    assert.ok(hd.length >= 10);
    for (const def of hd) {
      const vars = SAMPLE_VARS[def.key];
      assert.ok(vars, `${def.key} has sample values`);
      for (const { tag } of def.tags) if (tag !== "org_name") assert.ok(tag in vars, `${def.key}: ${tag} sampled`);
      for (const m of `${def.subject}\n${def.body}`.matchAll(/\{\{\s*(\w+)\s*\}\}/g)) {
        assert.ok(def.tags.some((t) => t.tag === m[1]), `${def.key}: {{${m[1]}}} documented`);
      }
    }
  });

  test("a markdown-ish subject and message stay text", async () => {
    const vars = {
      ...SAMPLE_VARS.hd_reply,
      subject: "**Urgent** [click](https://evil.example) <b>now</b>",
      author_name: "Eve <eve@example.test>",
      message: "Line one\n[x](https://evil.example)\n<img src=x onerror=alert(1)>",
      ticket_url: "https://docs.example.test/help/requests/1047",
    };
    const { subject, html, text } = await renderEmail("hd_reply", vars, "https://docs.example.test");
    assert.ok(subject.includes("Re: **Urgent** [click](https://evil.example) <b>now</b> [#1047 ref:"), subject);
    assert.ok(!html.includes('href="https://evil.example"'), "no link from a typed subject or message");
    assert.ok(!/<img|<b>now/.test(html), "no markup from typed values");
    assert.ok(html.includes("Eve &lt;eve@example.test&gt;") && html.includes("Line one<br>"), html);
    assert.ok(html.includes('href="https://docs.example.test/help/requests/1047"'), "our own link stays a link");
    assert.ok(text.includes("<img src=x onerror=alert(1)>"), "the text part is verbatim");
  });

  test("optional tags render blank, never raw", async () => {
    const { subject, text } = await renderEmail(
      "hd_request_received",
      { ticket_number: "1", subject: "S", team_name: "IT", ticket_url: "/help/requests/1", thread_ref: "" },
      ""
    );
    assert.ok(!/\{\{/.test(subject + text), subject + text);
  });
});

describe("macros and automations (pure)", () => {
  const ctx = {
    requester: { name: "Matthew *Felix*", email: "m@example.test" },
    ticket: { number: 1047, subject: "VPN [drops]", status: "pending" as const, priority: "high" as const },
    team: { name: "IT" },
    agent: { name: "Priya Shah", email: "p@example.test" },
    org: { name: "Acme" },
    origin: "https://docs.example.test",
  };

  test("placeholders fill, escape, and unknown ones stay visible", () => {
    const out = renderMacro(
      "Hi {{requester.first_name}}, about #{{ticket.number}} ({{ticket.subject}}): {{ticket.status}}, {{ticket.priority}}. {{ticket.url}} {{ agent.name }} {{agent.first_name}} {{team.name}} {{org.name}} {{requester.name}} {{nope.tag}}",
      ctx
    );
    assert.equal(
      out,
      "Hi Matthew, about #1047 (VPN \\[drops\\]): Waiting on you, High. https://docs.example.test/help/requests/1047 Priya Shah Priya IT Acme Matthew \\*Felix\\* {{nope.tag}}"
    );
    assert.equal(escapeInline("a\nb"), "a b");
  });

  test("macro actions are checked", () => {
    assert.equal(validateMacroActions({ status: "solved", tags_add: ["VPN fix", "vpn-fix"] }).ok, true);
    assert.deepEqual((validateMacroActions({ tags_add: ["VPN fix", "vpn-fix"] }) as { value: { tags_add: string[] } }).value.tags_add, ["vpn-fix"]);
    assert.equal(validateMacroActions({ status: "gone" }).ok, false);
    assert.equal(validateMacroActions({ delete: true }).ok, false);
  });

  test("conditions: every list given, any value within it; keywords are whole words", () => {
    const t = { team_id: 3, category: "Network", priority: "normal" as const, request_type_id: null, source: "email" as const, subject: "VPN keeps dropping", body: "since Monday" };
    assert.equal(automationMatches({}, t), true);
    assert.equal(automationMatches({ team_ids: [3, 4], keywords: ["vpn", "wifi"] }, t), true);
    assert.equal(automationMatches({ team_ids: [3], sources: ["portal"] }, t), false);
    assert.equal(automationMatches({ categories: ["network"] }, t), true);
    assert.equal(automationMatches({ request_type_ids: [1] }, t), false);
    assert.equal(keywordHit(["vpn"], "my vpnclient"), false);
    assert.equal(keywordHit(["c++"], "need c++ help"), true);
  });

  test("effective patch drops what the ticket already has", () => {
    const t = { team_id: 3, assignee_id: null, priority: "high" as const, status: "open" as const, category: "", tags: ["vpn"] };
    assert.deepEqual(effectivePatch({ priority: "high", team_id: 3, tags_add: ["vpn"] }, t), {});
    assert.deepEqual(effectivePatch({ priority: "urgent", tags_add: ["vpn", "network"] }, t), { priority: "urgent", tags: ["vpn", "network"] });
  });

  test("automation input is checked", () => {
    assert.equal(validateConditions({ priorities: ["urgent"], keywords: [" vpn ", "VPN"] }).ok, true);
    assert.deepEqual((validateConditions({ keywords: [" vpn ", "VPN"] }) as { value: { keywords: string[] } }).value.keywords, ["vpn"]);
    assert.equal(validateConditions({ priorities: ["meh"] }).ok, false);
    assert.equal(validateConditions({ secret: 1 }).ok, false);
    assert.equal(validateActions({}).ok, false);
    assert.equal(validateActions({ notify: "everyone" }).ok, false);
    assert.equal(validateActions({ notify: { user_id: 5 }, internal_note: "check" }).ok, true);
  });
});

describe("report helpers", () => {
  test("median and ranges", () => {
    assert.equal(median([]), null);
    assert.equal(median([5, 1, 3]), 3);
    assert.equal(median([1, 2, 3, 4]), 3);
    const r = parseReportRange(new URLSearchParams("from=2026-01-01&to=2026-01-31&team=4"), "UTC");
    assert.deepEqual(r, { ok: true, range: { from: "2026-01-01", to: "2026-01-31", team_id: 4 } });
    assert.equal(parseReportRange(new URLSearchParams("from=2026-02-01&to=2026-01-01"), "UTC").ok, false);
    assert.equal(parseReportRange(new URLSearchParams("from=2024-01-01&to=2026-01-01"), "UTC").ok, false);
    const d = parseReportRange(new URLSearchParams(""), "UTC", Date.parse("2026-11-06T12:00:00Z"));
    assert.deepEqual(d, { ok: true, range: { from: "2026-10-08", to: "2026-11-06", team_id: null } });
  });
});
