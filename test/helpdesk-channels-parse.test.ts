// Helpdesk 1.19.0, channels (agent C), the pure half: what each email
// provider posts becomes one InboundEmail; an email's HTML never survives
// as markup; a reply's quoted history is cut; text is stored as markdown
// that renders as exactly that text; reply tokens are found wherever a mail
// client leaves them; the attachment plan keeps only what it should; the
// hd_* templates keep a typed subject as typed and escape it in the html;
// macro placeholders fill and escape; automation conditions match.
//
// Run: DATABASE_URL=… npx tsx --tsconfig ./tsconfig.test.json --test test/helpdesk-channels-parse.test.ts

