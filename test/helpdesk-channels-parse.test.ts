const TOKEN = "k7q2xz9m4pqa1b2c";

function email(over: Partial<InboundEmail> = {}): InboundEmail {
  return {
    provider: "generic",
    from: { email: "matthew@example.test", name: "Matthew Felix" },
    to: [{ email: "help@example.test", name: "" }],
    cc: [],
    recipients: [],
    subject: "VPN drops",
    text: "It drops every few minutes.",
    html: "",
    stripped: "",
    messageId: "abc@mail.example.test",
    inReplyTo: "",
    references: [],
    headers: {},
    files: [],
    ...over,
  };
}

const PNG = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(8000, 1)]);
const PDF = Buffer.concat([Buffer.from("%PDF-1.7\n"), Buffer.alloc(100, 32)]);

